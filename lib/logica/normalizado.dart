final _marcas = RegExp('[\u0300-\u036f]');

String sinTildes(String texto) {
  final minusculas = texto.toLowerCase().replaceAll(_marcas, '');
  final salida = StringBuffer();
  for (final letra in minusculas.split('')) {
    salida.write(_equivalencias[letra] ?? letra);
  }
  return salida.toString();
}
